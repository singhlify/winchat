"""Write every copy of the eval metrics from one generated source.

    uv run --project backend python scripts/update_metrics.py backend/eval-report.json
    uv run --project backend python scripts/update_metrics.py --check

Outputs:
  docs/eval-report.md                     the full table, per category
  README.md                               the aggregate table, between markers
  frontend/src/lib/metrics.generated.ts   the three figures the landing page shows

--check regenerates into memory and exits non-zero if any file on disk differs, so a hand
edit to one copy fails CI instead of drifting.
"""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "backend" / "src"))

from winchat_api.evals.report import Proportion, build_markdown, wilson  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
REPORT_JSON = ROOT / "backend" / "eval-report.json"
DOCS_TABLE = ROOT / "docs" / "eval-report.md"
README = ROOT / "README.md"
FRONTEND = ROOT / "frontend" / "src" / "lib" / "metrics.generated.ts"

BEGIN = "<!-- BEGIN GENERATED METRICS -->"
END = "<!-- END GENERATED METRICS -->"

PLACEHOLDER = "Not yet generated. Run the commands below.\n"


def _counts(cases: list[dict], key: str) -> tuple[int, int]:
    scored = [c for c in cases if c.get(key) is not None]
    return sum(1 for c in scored if c[key]), len(scored)


def aggregate_table(payload: dict) -> str:
    cases = payload["cases"]
    rows = [
        Proportion("retrieval recall", *_counts(cases, "retrieval_hit")),
        Proportion("deterministic checks", *_counts(cases, "deterministic")),
        Proportion("refusal accuracy", *_counts(cases, "refusal_correct")),
        Proportion("faithfulness", *_counts(cases, "faithful")),
        Proportion("correctness", *_counts(cases, "correct")),
    ]
    lines = [
        f"Generated {payload.get('generated_at', 'unknown')} against model "
        f"`{payload['model']}`, judged by `{payload['judge_model']}`.",
        "",
        "| metric | estimate | passed/total | 95% interval |",
        "|---|---|---|---|",
    ]
    for row in rows:
        if row.denominator == 0:
            continue
        low, high = row.interval
        lines.append(
            f"| {row.label} | {row.point:.1%} | {row.numerator}/{row.denominator} "
            f"| {low:.1%} to {high:.1%} |"
        )
    n = len(cases)
    lines += [
        "",
        f"The graded set is {n} hand-written cases. At this sample size the 95% intervals "
        "above span several percentage points, and a single case moves a metric by roughly "
        f"{1 / n:.1%}. Per-category figures are in [docs/eval-report.md](docs/eval-report.md).",
    ]
    return "\n".join(lines)


def frontend_module(payload: dict | None) -> str:
    header = (
        "// Generated by scripts/update_metrics.py. Do not edit.\n"
        "// Regenerate after any eval run so the landing page cannot drift from the report.\n\n"
    )
    if payload is None:
        return (
            header + "export const METRICS_GENERATED_AT: string | null = null;\n\n"
            "export const METRICS: { value: string; label: string; detail: string }[] = [];\n"
        )
    cases = payload["cases"]
    picks = [
        ("retrieval_hit", "Retrieval recall", "the right article reached the model"),
        ("deterministic", "Deterministic checks", "citations, required facts, refusals"),
        ("correct", "Correctness", "judged against the retrieved sources"),
    ]
    entries = []
    for key, label, detail in picks:
        num, den = _counts(cases, key)
        if den == 0:
            continue
        low, high = wilson(num, den)
        entries.append(
            f'  {{ value: "{num / den:.0%}", label: "{label}", '
            f'detail: "{detail}, {num}/{den}, 95% interval {low:.0%} to {high:.0%}" }},'
        )
    return (
        header
        + f'export const METRICS_GENERATED_AT = "{payload.get("generated_at", "")}";\n\n'
        + "export const METRICS = [\n"
        + "\n".join(entries)
        + "\n];\n"
    )


def render(payload: dict | None) -> dict[Path, str]:
    if payload is None:
        readme_block = PLACEHOLDER
        docs = "# Evaluation report\n\n" + PLACEHOLDER
    else:
        readme_block = aggregate_table(payload) + "\n"
        docs = "# Evaluation report\n\n" + build_markdown(payload)

    readme = README.read_text(encoding="utf-8")
    start, end = readme.index(BEGIN), readme.index(END)
    readme = readme[: start + len(BEGIN)] + "\n" + readme_block + readme[end:]
    return {DOCS_TABLE: docs, README: readme, FRONTEND: frontend_module(payload)}


def main(argv: list[str]) -> int:
    check = "--check" in argv
    args = [a for a in argv[1:] if not a.startswith("-")]
    source = Path(args[0]) if args else REPORT_JSON
    payload = json.loads(source.read_text(encoding="utf-8")) if source.exists() else None

    if payload is None and not check:
        print(f"no eval report at {source}, writing placeholders", file=sys.stderr)

    stale = []
    for path, content in render(payload).items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        if check:
            stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")

    if stale:
        print(
            "These files disagree with the generated report:\n  "
            + "\n  ".join(str(p) for p in stale)
            + "\n\nRegenerate with:\n"
            "  uv run --project backend python scripts/update_metrics.py backend/eval-report.json",
            file=sys.stderr,
        )
        return 1
    if check:
        print("metrics are in sync")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
